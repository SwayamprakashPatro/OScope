// Tier 2B: RAID layouts, capacity, tolerance and XOR rebuild. Expected values derived by hand.
const R = require('../js/engines/raid.js');
let pass = 0, fail = 0;
const eq = (n, got, want) => { const ok = JSON.stringify(got) === JSON.stringify(want); ok ? pass++ : fail++; console.log((ok ? 'PASS ' : 'FAIL ') + n + (ok ? '' : ' got=' + JSON.stringify(got) + ' want=' + JSON.stringify(want))); };
const B = { level: '5', disks: 4, capacity: 1000, rate: 100, failed: '', data: '5 12 10 7 9 3 14 6 11' };
const go = (o) => R.run(Object.assign({}, B, o));
const kinds = (r, s) => r.rows[s].cells.map((c) => c.kind + (c.block !== undefined ? c.block : '')).join(' ');

let r = go({});
eq('RAID5 N=4 stripe 0: data 0,1,2 then parity on disk 3', kinds(r, 0), 'D0 D1 D2 P');
eq('stripe 1: parity on disk 2', kinds(r, 1), 'D3 D4 P D5');
eq('stripe 2: parity on disk 1', kinds(r, 2), 'D6 P D7 D8');
eq('stripe 3: parity on disk 0', kinds(r, 3), 'P D9 D10 D11');
eq('stripe 4: parity wraps back to disk 3', kinds(r, 4), 'D12 D13 D14 P');
eq('parity of bytes 5,12,10 = 3', r.rows[0].parity, 3);
eq('parity of 7,9,3 = 13', r.rows[1].parity, 13);
eq('RAID5 usable = 3 x 1000, tolerates 1', [r.perf.usable, r.perf.tolMin], [3000, 1]);
eq('RAID5 small write = 4 I/Os', r.perf.small, 4);
r = go({ failed: '1' });
eq('RAID5 survives one failure', r.survives, true);
eq('disk 1 in stripe 0 held byte 12; XOR of 5, 10, parity 3 rebuilds it', r.recovered.find((x) => x.s === 0 && x.disk === 1), { s: 0, disk: 1, kind: 'D', original: 12, value: 12, how: 'XOR of the surviving blocks in the stripe', ok: true });
eq('every recovered block matches the original', r.recovered.every((x) => x.ok), true);
eq('parity block on the failed disk (stripe 2) is also recomputed', r.recovered.find((x) => x.s === 2 && x.disk === 1).kind, 'P');
r = go({ failed: '1 2' });
eq('RAID5 does not survive two failures', r.survives, false);
eq('two failures: stripe 0 blocks cannot be recomputed', r.recovered.filter((x) => x.s === 0).every((x) => x.value === null), true);
r = go({ level: '0', failed: '2' });
eq('RAID0 dies with any failure; usable = N x C; no tolerance', [r.survives, r.perf.usable, r.perf.tolMin], [false, 4000, 0]);
eq('RAID0 layout is plain striping', kinds(r, 1), 'D4 D5 D6 D7');
r = go({ level: '1', disks: 2 });
eq('RAID1 usable = C, tolerates N-1 = 1', [r.perf.usable, r.perf.tolMin], [1000, 1]);
eq('RAID1 mirrors the same block', kinds(r, 0), 'D0 M0');
r = go({ level: '1', disks: 3, failed: '0 1' });
eq('RAID1 with 3 disks survives 2 failures, rebuilds from the last copy', [r.survives, r.recovered.every((x) => x.ok)], [true, true]);
r = go({ level: '10', failed: '0 2' });
eq('RAID10 N=4 layout: pairs hold blocks 0,1', kinds(r, 0), 'D0 M0 D1 M1');
eq('RAID10 survives failures in different pairs', [r.survives, r.recovered.every((x) => x.ok)], [true, true]);
r = go({ level: '10', failed: '0 1' });
eq('RAID10 loses data when both disks of a pair fail', r.survives, false);
eq('RAID10 usable = N/2 x C; guaranteed tolerance 1, best case 2', [r.perf.usable, r.perf.tolMin, r.perf.tolMax], [2000, 1, 2]);
r = go({ level: '6', disks: 5 });
eq('RAID6 N=5 stripe 0: P on disk 4, Q on disk 0 (wraps)', kinds(r, 0), 'Q D0 D1 D2 P');
eq('RAID6 stripe 1: P on 3, Q on 4', kinds(r, 1), 'D3 D4 D5 P Q');
eq('RAID6 usable = (N-2) x C, tolerates 2, small write 6', [r.perf.usable, r.perf.tolMin, r.perf.small], [3000, 2, 6]);
eq('RAID6 survives two failures', go({ level: '6', disks: 5, failed: '0 3' }).survives, true);
eq('RAID6 does not survive three', go({ level: '6', disks: 5, failed: '0 1 3' }).survives, false);
eq('RAID6 single failure rebuilds via P', go({ level: '6', disks: 5, failed: '2' }).recovered.filter((x) => x.kind !== 'Q').every((x) => x.ok), true);
eq('rebuild time: 1000 GB at 100 MB/s = 1000*1024/100/3600 h', Math.abs(go({}).rebuildHours - 1000 * 1024 / 100 / 3600) < 1e-9, true);
eq('efficiency of RAID5 with 4 disks = 0.75', go({}).efficiency, 0.75);
eq('RAID5 needs 3 disks', go({ disks: 2 }).ok, false);
eq('RAID10 needs even', go({ level: '10', disks: 5 }).ok, false);
eq('RAID6 needs 4', go({ level: '6', disks: 3 }).ok, false);
eq('failed disk out of range', go({ failed: '9' }).ok, false);
eq('bad data byte', go({ data: '300' }).ok, false);
eq('bad level', go({ level: '7' }).ok, false);
for (let t = 0; t < 400; t++) { // random: RAID5 XOR rebuild always reproduces the original; parity XOR of all cells in a stripe is 0
  const N = 3 + Math.floor(Math.random() * 6), data = Array.from({ length: 12 }, () => Math.floor(Math.random() * 256)).join(' '), f = Math.floor(Math.random() * N);
  const rr = go({ disks: N, data, failed: String(f) }); let ok = rr.ok && rr.survives && rr.recovered.every((x) => x.ok);
  const clean = go({ disks: N, data }); clean.rows.forEach((row) => { if (row.cells.reduce((a, c) => a ^ c.value, 0) !== 0) ok = false; });
  if (!ok) { fail++; console.log('FAIL raid5 random', N, data, f); } else pass++;
}
console.log(`${pass} passed, ${fail} failed`); process.exit(fail ? 1 : 0);
