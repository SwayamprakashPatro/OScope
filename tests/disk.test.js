const D = require('../js/engines/disk.js');
let pass = 0, fail = 0;
const eq = (n, got, want) => { const ok = JSON.stringify(got) === JSON.stringify(want); ok ? pass++ : fail++; console.log((ok ? 'PASS ' : 'FAIL ') + n + (ok ? '' : ' got=' + JSON.stringify(got) + ' want=' + JSON.stringify(want))); };
const Q = D.parseQueue('98 183 37 122 14 124 65 67');
const run = (a, o) => D.simulate(Q, 53, 200, a, o);
eq('FCFS = 640', run('fcfs').total, 640);
eq('SSTF = 236', run('sstf').total, 236);
eq('SSTF order', run('sstf').moves.map((m) => m.to), [65, 67, 37, 14, 98, 122, 124, 183]);
eq('SCAN down = 236', run('scan', { direction: 'down' }).total, 236);
eq('SCAN down visits edge 0', run('scan', { direction: 'down' }).moves.map((m) => m.to), [37, 14, 0, 65, 67, 98, 122, 124, 183]);
eq('SCAN up = 331', run('scan', { direction: 'up' }).total, 331);
eq('C-SCAN up, jump counted = 382', run('cscan', { direction: 'up', countJump: true }).total, 382);
eq('C-SCAN up, jump not counted = 183', run('cscan', { direction: 'up', countJump: false }).total, 183);
eq('LOOK down = 208', run('look', { direction: 'down' }).total, 208);
eq('LOOK up = 299', run('look', { direction: 'up' }).total, 299);
eq('C-LOOK up, jump counted = 322', run('clook', { direction: 'up', countJump: true }).total, 322);
eq('C-LOOK up, jump not counted = 153', run('clook', { direction: 'up', countJump: false }).total, 153);
eq('C-LOOK serves everything', run('clook', { direction: 'up' }).frames.slice(-1)[0].pending, []);
const st = D.simulate(D.parseQueue('199 98 102 97 103 96 104'), 100, 200, 'sstf');
eq('SSTF starves 199 until last', st.moves[st.moves.length - 1].to, 199);
const e = D.simulate(D.parseQueue('10 40 25 70 5'), 0, 100, 'scan', { direction: 'up' });
eq('Head at 0, SCAN up: 5,10,25,40,70, then edge 99', e.moves.map((m) => m.to), [5, 10, 25, 40, 70, 99]);
eq('Validation: request outside disk', D.validate([250], 10, 200).ok, false);
eq('Validation ok', D.validate([5, 10], 3, 200).ok, true);
console.log('\n' + pass + ' passed, ' + fail + ' failed'); process.exit(fail ? 1 : 0);
